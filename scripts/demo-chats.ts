/** In the export-tool format: "name date time", the text, a blank line. */
function exportText(lines: Line[], me: string, them: string) {
  return lines
    .map(
      ([date, time, who, text]) =>
        `${who === "me" ? me : them} ${date} ${time}:00\n${text}\n`,
    )
    .join("\n");
}

